//! VSIDL runtime config generator
//! Reads and parses a VSIDL catalog and its dependencies. Outputs runtime configuration files used by SDV agents

mod android_bp;
mod generator;

use std::path::PathBuf;

use anyhow::anyhow;
use clap::Parser;
use clap::ValueEnum;

use android_bp::resolve_build_path;
use vsidl_v1_parser::remove_non_google_options::RemoveNonGoogleOptions;
use vsidl_v1_parser::service_bundle_symbol::ServiceBundleSource;
use vsidl_v1_parser::service_bundle_symbol::ServiceBundleSymbol;
use vsidlc_cli::VsidlcCommonCli;

#[derive(Debug, Clone, Copy, ValueEnum, PartialEq, Eq)]
enum Variant {
    RuntimeConfig,
    RuntimeConfigPrebuilts,
}

///Client args for the VSIDL parser.
#[derive(Parser, Clone)]
pub struct Cli {
    #[arg(long)]
    vsidl_path: Option<PathBuf>,

    #[arg(long)]
    catalog_path: PathBuf,

    #[arg(long)]
    output_path: PathBuf,

    /// Optional. Specifies the directories of the dependent protos outside of the `catalog_path`.Each directory must contain an `Android.bp` file with a `rust_protobuf` build target to generate Rust API for the dependent protos. In the case of multi-layered dependency graph, please pass in one list with all the directories in the graph.
    #[arg(long, num_args(1..), value_delimiter = ',')]
    dependency_catalog_path: Vec<PathBuf>,

    /// Optional. Defaults to `RuntimeConfig`. Specifies the mode in which the runtime config generator should run. `RuntimeConfig` generates runtime config files for SOME/IP and Diagnostics. `RuntimeConfigPrebuilts` generates build file(s) containing `prebuilt` modules that can be used to include the file(s) generated by `RuntimeConfig` variant in other modules or in the VM image itself.
    #[arg(value_enum,long, default_value_t = Variant::RuntimeConfig)]
    variant: Variant,

    /// Optional argument specifying service bundle for which to run the runtime config generator.
    #[arg(long)]
    service_bundle_name: Option<String>,

    /// Optional argument (in addition to service bundle name argument) specifying service bundle package name for which to run the runtime config generator.
    #[arg(long)]
    package_name: Option<String>,

    /// Needs to be defined when using the 'RuntimeConfigPrebuilts' mode.
    #[arg(long)]
    filegroup: Option<String>,

    /// Ignore context condition findings with the given IDs
    #[arg(short, long)]
    ignore: Vec<String>,
}

impl From<Cli> for VsidlcCommonCli {
    fn from(cli: Cli) -> Self {
        VsidlcCommonCli {
            catalog_path: cli.catalog_path,
            output_path: cli.output_path,
            ignore: cli.ignore,
            dependency_catalog_path: cli.dependency_catalog_path,
            ..Default::default()
        }
    }
}

fn get_cli_command_string(cli: &Cli) -> String {
    let command_str_vsidl_path = match &cli.vsidl_path {
        Some(path) => format!("--vsidl-path {}", resolve_build_path(path)),
        None => "".to_owned(),
    };
    let mut command_str_dependency_catalog_path = "".to_owned();
    for path in &cli.dependency_catalog_path {
        command_str_dependency_catalog_path += &format!(
            "--dependency-catalog-path ${{ANDROID_BUILD_TOP}}/{} ",
            resolve_build_path(path)
        );
    }
    let command_str_service_bundle_name = match &cli.service_bundle_name {
        Some(service_bundle_name) => format!("--service-bundle-name {service_bundle_name}"),
        None => "".to_owned(),
    };
    let command_str_package_name = match &cli.package_name {
        Some(package_name) => format!("--package-name {package_name}"),
        None => "".to_owned(),
    };
    let command_str_filegroup = match &cli.filegroup {
        Some(filegroup) => format!("--filegroup {filegroup}"),
        None => "".to_owned(),
    };

    format!("vsidl_rc_generator --catalog-path ${{ANDROID_BUILD_TOP}}/{} --output-path ${{ANDROID_BUILD_TOP}}/{} --variant runtime-config-prebuilts {} {} {} {} {}",
        resolve_build_path(&cli.catalog_path),
        resolve_build_path(&cli.output_path),
        command_str_vsidl_path,
        command_str_dependency_catalog_path,
        command_str_service_bundle_name,
        command_str_package_name,
        command_str_filegroup,
    )
}

/// Executes the VSIDL RC (Runtime Config) Generator
/// # Arguments
///
/// *   `cli` - The `Cli` struct containing the command-line arguments.
///
/// # Returns
///
/// *   `Ok(())` - If the execution completes successfully.
/// *   `Err(anyhow::Error)` - If an error occurs during any of the steps, such
///     as catalog parsing, symbol table creation.
pub fn execute(cli: Cli) -> anyhow::Result<()> {
    eprintln!("Parsing catalog from folder '{}'.", &cli.catalog_path.display());

    let dependencies: Vec<&std::path::Path> =
        cli.dependency_catalog_path.iter().map(PathBuf::as_path).collect();

    let vcli = VsidlcCommonCli::from(cli.clone());
    let mut catalog = vcli.create_catalog(cli.vsidl_path.clone())?;
    RemoveNonGoogleOptions::traverse(&mut catalog);
    let catalog = catalog; // make catalog immutable
    let symbol_table = vcli.create_symbol_table_from_catalog(&catalog)?;

    let mut bundles: Vec<ServiceBundleSymbol> = symbol_table
        .get_all_service_bundle_symbols()
        .iter()
        .filter(|bundle| bundle.source == ServiceBundleSource::CATALOG)
        .cloned()
        .cloned()
        .collect();
    bundles.sort_by_key(|sb| sb.file_path.clone());

    let output_path = cli.output_path.as_path();
    let service_bundle_name = cli.service_bundle_name.clone();
    let package_name = cli.package_name.clone();
    let filegroup = cli.filegroup.clone();

    if cli.variant == Variant::RuntimeConfig && filegroup.is_some() {
        return Err(anyhow!(
            "When running in RuntimeConfig mode, filegroup should not be specified"
        ));
    }
    if cli.variant == Variant::RuntimeConfigPrebuilts && filegroup.is_none() {
        return Err(anyhow!(
            "When running in RuntimeConfigPrebuilts mode, at filegroup must be specified"
        ));
    }

    match cli.variant {
        Variant::RuntimeConfig => crate::generator::generate_runtime_config(
            &catalog,
            &symbol_table,
            &bundles,
            output_path,
            service_bundle_name,
            package_name,
        )?,
        Variant::RuntimeConfigPrebuilts => crate::generator::generate_runtime_config_prebuilts(
            cli.catalog_path.as_path(),
            &catalog,
            &symbol_table,
            &bundles,
            output_path,
            &filegroup.unwrap(),
            &dependencies,
            &vec![
                "This file was generated using the following command:".to_owned(),
                get_cli_command_string(&cli),
            ],
        )?,
    };

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::Parser;
    use std::path::PathBuf;

    #[test]
    fn test_cli_to_vsidlc_common_cli_forwarding() {
        let cli = Cli::parse_from([
            "fakeCommand",
            "--catalog-path",
            "catalog_path",
            "--output-path",
            "output_path",
            "--dependency-catalog-path",
            "dep1",
            "--dependency-catalog-path",
            "dep2",
            "--ignore",
            "ignore1",
            "--ignore",
            "ignore2",
        ]);

        let common_cli = VsidlcCommonCli::from(cli.clone());

        assert_eq!(common_cli.catalog_path, PathBuf::from("catalog_path"));
        assert_eq!(common_cli.output_path, PathBuf::from("output_path"));
        assert_eq!(
            common_cli.dependency_catalog_path,
            vec![PathBuf::from("dep1"), PathBuf::from("dep2")]
        );
        assert_eq!(common_cli.ignore, vec!["ignore1".to_string(), "ignore2".to_string()]);
    }
}
