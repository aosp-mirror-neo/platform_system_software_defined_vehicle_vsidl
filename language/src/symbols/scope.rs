use super::symbol::{SymbolId, SymbolKind};
use crate::SymbolTable;
use indexmap::IndexMap;

/// A unique identifier for a [Scope] within a [SymbolTable].
///
/// It wraps a `usize` index used internally by the [SymbolTable].
#[derive(Debug, Default, Clone, PartialEq, Eq, Hash)]
pub struct ScopeId(pub usize);

/// Represents a lexical scope within the symbol table.
///
/// Scopes hold symbols and impact their visibility, e.g., by defining the namespace hierarchy.
/// They are organized in a tree structure where each scope (except the global scope)
/// has an enclosing parent scope and can contain subscopes.
///
/// Scopes can be associated with specific language constructs (like a service bundle)
/// via the [Scope::spanning_symbol] field.
#[derive(Debug, Clone)]
pub struct Scope {
    /// The unique identifier for this scope.
    pub id: ScopeId,
    /// The name of the scope (e.g., package name, service bundle name). Empty for the global scope.
    pub name: String,
    /// The IDs of the scopes directly nested within this scope.
    pub subscopes: Vec<ScopeId>,
    /// The ID of the scope that directly contains this scope. `None` for the global scope.
    pub enclosing_scope: Option<ScopeId>,
    /// A map of symbol names to a list of [SymbolId]s defined within this scope.
    /// A single name might map to multiple symbols (e.g., different symbol kinds).
    pub symbols: IndexMap<String, Vec<SymbolId>>,
    /// The ID of the symbol that defines this scope, if any (e.g., a [ServiceBundleSymbol]).
    pub spanning_symbol: Option<SymbolId>,
}

/// Macro to generate resolver functions for specific symbol types within a scope.
///
/// This macro simplifies the creation of functions like `resolve_service_bundle`,
/// `resolve_publisher`, etc., which find symbols of a specific kind by name starting from
/// the current scope.
macro_rules! implement_resolver {
    ($func_name:ident, $symbol_kind:path, $symbol_type:ty) => {
        /// Resolves a name to symbols of a specific type within this scope and its enclosing scopes.
        ///
        /// This function searches for symbols matching the given `name` and the specific symbol type
        /// (e.g., [ServiceBundleSymbol], [PublisherSymbol]) starting from the current scope and moving
        /// up the scope hierarchy until the global scope is reached or the name is found.
        ///
        /// # Parameters
        ///
        /// * `symbol_table` - The symbol table containing all scopes and symbols.
        /// * `name` - The name of the symbol to resolve. Can be an unqualified name, or a partially or fully qualified name.
        ///
        /// # Returns
        ///
        /// A `Vec` containing clones of the resolved symbols of the specified type.
        /// Returns an empty `Vec` if no matching symbol is found.
        pub fn $func_name(
            &self,
            symbol_table: &crate::symbol_table::SymbolTable,
            name: impl Into<String>,
        ) -> Vec<$symbol_type> {
            symbol_table
                .resolve(&self.id, &name.into(), false)
                .into_iter()
                .filter_map(|symbol| match symbol {
                    $symbol_kind(specific_symbol) => Some(specific_symbol),
                    _ => None,
                })
                .map(|symbol| symbol.clone())
                .collect()
        }
    };
}

impl Scope {
    // The following functions are generated by the `implement_resolver` macro.
    // They provide convenient methods to resolve specific symbol types by name.

    implement_resolver!(resolve_service_bundle, SymbolKind::ServiceBundle, ServiceBundleSymbol);
    implement_resolver!(resolve_publisher, SymbolKind::Publisher, PublisherSymbol);
    implement_resolver!(resolve_rpc_channel, SymbolKind::RpcChannel, RpcChannelSymbol);
    implement_resolver!(resolve_topic, SymbolKind::Topic, TopicSymbol);
    implement_resolver!(resolve_rpc_server, SymbolKind::RpcServer, RpcServerSymbol);
    implement_resolver!(resolve_rpc_client, SymbolKind::RpcClient, RpcClientSymbol);
    implement_resolver!(resolve_proto_message, SymbolKind::ProtoMessage, ProtoMessageSymbol);
    implement_resolver!(resolve_proto_enum, SymbolKind::ProtoEnum, ProtoEnumSymbol);
    implement_resolver!(
        resolve_proto_publication,
        SymbolKind::ProtoPublication,
        ProtoPublicationSymbol
    );
    implement_resolver!(
        resolve_proto_rpc_service,
        SymbolKind::ProtoRpcService,
        ProtoRpcServiceSymbol
    );

    /// Returns the fully-qualified name of the scope.
    ///
    /// This constructs the name by traversing up the scope hierarchy from the current scope
    /// to the global scope and joining the non-empty scope names with dots (`.`).
    ///
    /// # Parameters
    ///
    /// * `symbol_table` - The symbol table containing all scopes.
    ///
    /// # Returns
    ///
    /// A `String` representing the fully-qualified name (e.g., "com.google.sdv").
    /// Returns an empty string for the global scope.
    pub fn full_name(&self, symbol_table: &SymbolTable) -> String {
        let mut parts = Vec::new();

        let mut current_scope_id: Option<ScopeId> = Some(self.id.clone());
        while let Some(scope_id) = current_scope_id {
            if let Some(scope) = symbol_table.get_scope(&scope_id) {
                if !scope.name.is_empty() {
                    parts.push(scope.name.clone());
                }
                current_scope_id = scope.enclosing_scope.clone();
            } else {
                break; // Should not happen in a well-formed symbol table, but break defensively.
            }
        }
        parts.reverse(); // Reverse to get the correct order (outermost scope first)
        parts.join(".")
    }
}

#[cfg(test)]
mod test {
    use super::*;

    #[test]
    fn test_full_name_in_global_scope() {
        // GIVEN a symbol table with global scope
        let mut symbol_table = SymbolTable::default();
        let global_scope_id = symbol_table.create_scope("".to_string());
        let scope = symbol_table.get_scope(&global_scope_id).unwrap();

        // WHEN getting the name of the global scope
        let result = scope.full_name(&symbol_table);

        // THEN the name of the global scope should be empty
        assert_eq!(result, "");
    }

    #[test]
    fn test_full_name_symbol_in_nested_scopes() {
        // GIVEN a symbol table with nested scopes
        let mut symbol_table = SymbolTable::default();
        let global_scope_id = symbol_table.create_scope("".to_string());
        let com_scope_id = symbol_table.create_scope("com".to_string());
        let google_scope_id = symbol_table.create_scope("google".to_string());
        let sdv_scope_id = symbol_table.create_scope("sdv".to_string());
        symbol_table.add_subscope(&global_scope_id, &com_scope_id);
        symbol_table.add_subscope(&com_scope_id, &google_scope_id);
        symbol_table.add_subscope(&google_scope_id, &sdv_scope_id);
        let sdv_scope = symbol_table.get_scope(&sdv_scope_id).unwrap();

        // WHEN getting the full name of the innermost scope
        let result = sdv_scope.full_name(&symbol_table);

        // THEN the full name should be correctly constructed
        assert_eq!(result, "com.google.sdv");
    }

    #[test]
    fn test_full_name_symbol_in_nested_scopes_with_anonymous_scope() {
        // GIVEN a symbol table with nested scopes including an anonymous one
        let mut symbol_table = SymbolTable::default();
        let global_scope_id = symbol_table.create_scope("".to_string());
        let com_scope_id = symbol_table.create_scope("com".to_string());
        let google_scope_id = symbol_table.create_scope("google".to_string());
        let anonymous_scope_id = symbol_table.create_scope("".to_string());
        let sdv_scope_id = symbol_table.create_scope("sdv".to_string());
        symbol_table.add_subscope(&global_scope_id, &com_scope_id);
        symbol_table.add_subscope(&com_scope_id, &google_scope_id);
        symbol_table.add_subscope(&google_scope_id, &anonymous_scope_id);
        symbol_table.add_subscope(&anonymous_scope_id, &sdv_scope_id);
        let sdv_scope = symbol_table.get_scope(&sdv_scope_id).unwrap();

        // WHEN getting the full name of the innermost scope
        let result = sdv_scope.full_name(&symbol_table);

        // THEN the full name should skip the anonymous scope
        assert_eq!(result, "com.google.sdv");
    }

    #[test]
    fn test_full_name_with_inconsistent_symbol_table() {
        // GIVEN a symbol table where a scope's ID does not exist
        let symbol_table = SymbolTable::default();

        // GIVEN a scope not known to the symbol table
        let scope = Scope {
            id: ScopeId(999),
            name: "test".to_string(),
            subscopes: Vec::new(),
            enclosing_scope: None,
            symbols: IndexMap::new(),
            spanning_symbol: None,
        };

        // WHEN getting the full name of the scope
        let result = scope.full_name(&symbol_table);

        // THEN no name can be calculated
        assert_eq!(result, "");
    }
}
