use heck::ToKebabCase;
use heck::ToSnakeCase;

/// Generates the crate and library name for a service bundle based on its package, name, and optional custom name.
///
/// If a `custom_crate_name` is provided, it is converted to snake_case and used.
/// Otherwise, the name is derived by concatenating the service bundle's package name (with '.' replaced by '_')
/// and its name, then converting the result to snake_case.
///
/// # Parameters
///
/// * `service_bundle_package_name` - The package name of the service bundle (e.g., "com.example.services").
/// * `service_bundle_name` - The name of the service bundle (e.g., "MyServiceBundle").
/// * `custom_crate_name` - An optional custom name provided in the build configuration. If empty, the name is generated.
///
/// # Returns
///
/// A `String` representing the snake_case crate and library name to be used in generated Android.bp files.
///
/// # Examples
///
/// ```rust
/// # use vsidl_v1_parser::name_utils::get_crate_and_library_name;
/// let package = "com.example.vehicle";
/// let bundle_name = "ClimateControl";
/// let custom_name = "";
/// let generated_name = get_crate_and_library_name(package, &bundle_name.to_string(), &custom_name.to_string());
/// assert_eq!(generated_name, "com_example_vehicle_climate_control");
///
/// let custom_name = "my_climate_lib";
/// let generated_name_custom = get_crate_and_library_name(package, &bundle_name.to_string(), &custom_name.to_string());
/// assert_eq!(generated_name_custom, "my_climate_lib");
///
/// let custom_name_needs_case = "MyClimateLib";
/// let generated_name_custom_case = get_crate_and_library_name(package, &bundle_name.to_string(), &custom_name_needs_case.to_string());
/// assert_eq!(generated_name_custom_case, "my_climate_lib");
/// ```
pub fn get_crate_and_library_name(
    service_bundle_package_name: &str,
    service_bundle_name: &String,
    custom_crate_name: &String,
) -> String {
    if custom_crate_name.is_empty() {
        format!("{}_{}", service_bundle_package_name.replace('.', "_"), service_bundle_name)
            .to_snake_case()
    } else {
        custom_crate_name.to_owned().to_snake_case()
    }
}

/// Converts a potentially short type name into a fully-qualified name (FQN) using a package context.
///
/// If the input `name` already contains a '.', it is assumed to be fully qualified and returned as is.
/// Otherwise, it prepends the `package` name followed by a '.' to the `name`.
/// If the `name` is empty, an empty string is returned.
///
/// # Parameters
///
/// * `name` - The type name, which might be short (e.g., "MyType") or already fully qualified (e.g., "com.example.MyType").
/// * `package` - The package name to use as context if `name` is short (e.g., "com.example").
///
/// # Returns
///
/// A `String` representing the fully-qualified name.
///
/// # Examples
///
/// ```rust
/// # use vsidl_v1_parser::name_utils::name_to_fqn;
/// let name = "MyMessage";
/// let package = "com.example.protos";
/// let fqn = name_to_fqn(name, package);
/// assert_eq!(fqn, "com.example.protos.MyMessage");
///
/// let already_fqn = "google.protobuf.Empty";
/// let fqn_unchanged = name_to_fqn(already_fqn, package);
/// assert_eq!(fqn_unchanged, "google.protobuf.Empty");
///
/// let empty_name = "";
/// let fqn_empty = name_to_fqn(empty_name, package);
/// assert_eq!(fqn_empty, "");
/// ```
pub fn name_to_fqn(name: &str, package: &str) -> String {
    if !name.is_empty() && name.find('.').is_none() {
        format!("{package}.{name}")
    } else {
        String::from(name)
    }
}

/// Generates a service unit name from a fully qualified type name and a channel name.
///
/// The service unit name is generated by concatenating the fully qualified type name and the channel name,
/// separated by a hyphen, and then converting the result to kebab-case.
///
/// # Parameters
///
/// * `type_fqn` - The fully qualified type name (e.g., "com.example.MyType").
/// * `channel` - The channel name (e.g., "ChannelA").
///
/// # Returns
///
/// A string representing the service unit name in kebab-case (e.g., "com-example-my-type-channel-a").
///
/// # Examples
///
/// ```rust
/// # use vsidl_v1_parser::name_utils::format_service_unit_name;
/// let type_fqn = "com.example.vehicle.SensorData".to_string();
/// let channel = "FrontLeft".to_string();
/// let service_unit_name = format_service_unit_name(type_fqn, channel);
/// assert_eq!(service_unit_name, "com-example-vehicle-sensor-data-front-left");
///
/// let type_fqn_simple = "SimpleService".to_string();
/// let channel_unique = "UNIQUE".to_string();
/// let service_unit_name_simple = format_service_unit_name(type_fqn_simple, channel_unique);
/// assert_eq!(service_unit_name_simple, "simple-service-unique");
/// ```
pub fn format_service_unit_name(type_fqn: String, channel: String) -> String {
    format!("{type_fqn}-{channel}").to_kebab_case()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_get_crate_and_library_name_empty_custom_name() {
        assert_eq!(
            get_crate_and_library_name(
                "com.example.vehicle",
                &"ClimateControl".to_string(),
                &"".to_string()
            ),
            "com_example_vehicle_climate_control"
        );
    }

    #[test]
    fn test_get_crate_and_library_name_with_custom_name() {
        assert_eq!(
            get_crate_and_library_name(
                "com.example.vehicle",
                &"ClimateControl".to_string(),
                &"my_custom_climate_lib".to_string()
            ),
            "my_custom_climate_lib"
        );
    }

    #[test]
    fn test_get_crate_and_library_name_custom_name_needs_snake_case() {
        assert_eq!(
            get_crate_and_library_name(
                "com.example.vehicle",
                &"ClimateControl".to_string(),
                &"MyCustomClimateLib".to_string()
            ),
            "my_custom_climate_lib"
        );
    }

    #[test]
    fn test_get_crate_and_library_name_no_dots_in_package() {
        assert_eq!(
            get_crate_and_library_name("example", &"MyBundle".to_string(), &"".to_string()),
            "example_my_bundle"
        );
    }

    #[test]
    fn test_get_crate_and_library_name_empty_package() {
        assert_eq!(
            get_crate_and_library_name("", &"MyBundle".to_string(), &"".to_string()),
            "my_bundle"
        );
    }

    #[test]
    fn test_get_crate_and_library_name_empty_bundle_name() {
        assert_eq!(
            get_crate_and_library_name("com.example", &"".to_string(), &"".to_string()),
            "com_example"
        );
    }

    #[test]
    fn test_get_crate_and_library_name_empty_package_and_bundle_name() {
        assert_eq!(get_crate_and_library_name("", &"".to_string(), &"".to_string()), "");
    }

    #[test]
    fn test_name_to_fqn_short_name() {
        assert_eq!(name_to_fqn("MyType", "com.example"), "com.example.MyType");
    }

    #[test]
    fn test_name_to_fqn_already_qualified() {
        assert_eq!(name_to_fqn("com.example.MyType", "com.other"), "com.example.MyType");
    }

    #[test]
    fn test_name_to_fqn_empty_name() {
        assert_eq!(name_to_fqn("", "com.example"), "");
    }

    #[test]
    fn test_name_to_fqn_empty_package() {
        assert_eq!(name_to_fqn("MyType", ""), ".MyType");
    }

    #[test]
    fn test_name_to_fqn_name_starts_with_dot() {
        assert_eq!(name_to_fqn(".com.example.MyType", "com.other"), ".com.example.MyType");
    }

    #[test]
    fn test_format_service_unit_name_basic() {
        assert_eq!(
            format_service_unit_name("com.example.MyService".to_string(), "Channel1".to_string()),
            "com-example-my-service-channel1"
        );
    }

    #[test]
    fn test_format_service_unit_name_with_kebab_case_input() {
        assert_eq!(
            format_service_unit_name("already-kebab".to_string(), "is-fine".to_string()),
            "already-kebab-is-fine"
        );
    }
}
