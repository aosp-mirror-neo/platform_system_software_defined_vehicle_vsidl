//! Extracts all unit type form a catalog and dependencies

use crate::Catalog;
use crate::ProtoBuildTargetMetadata;

use anyhow::anyhow;
use indexmap::IndexMap;
use protobuf::descriptor::FileDescriptorProto;
use std::collections::HashMap;
use std::path::PathBuf;

/// Represents a Protobuf message along with metadata about the `.proto` file it is defined in.
///
/// This struct combines the basic identification of a message (name and package)
/// with build-related information provided by [ProtoMetadata].
#[derive(Debug, Clone, Eq, Hash, PartialEq)]
pub struct ProtoMessage {
    /// The unqualified name of the Protobuf message (e.g., "MyMessage").
    pub name: String,
    /// The package name declared in the `.proto` file (e.g., "com.example.protos").
    pub package: String,
    /// Metadata related to the build target and file location of this message.
    pub proto_metadata: ProtoMetadata,
}

#[derive(Default, Debug, Clone, Eq, Hash, PartialEq)]
/// Holds metadata related to the build target and file location of a Protobuf file.
///
/// This information is crucial for linking Protobuf definitions to their generated
/// code artifacts, especially in build systems like Android's Soong.
pub struct ProtoMetadata {
    /// The absolute path to the directory containing the `.proto` file.
    pub folder: PathBuf,
    /// The relative path of the `.proto` file within its source directory (e.g., "path/to/my_message.proto").
    pub filename: String,
    /// The name of the build target (e.g., `rust_protobuf` target name in `Android.bp`)
    /// responsible for compiling this `.proto` file.
    pub rust_build_target_name: Option<String>,
    /// The name of the Rust crate generated by the build target.
    pub rust_crate_name: Option<String>,
}

/// Finds all transitive proto dependencies for a given proto file.
///
/// This function traverses the import graph starting from `proto_filename`, collecting
/// metadata for all imported `.proto` files. It excludes Google's well-known Protobuf types
/// (like `google.protobuf.Empty`) as they are implicitly available.
///
/// # Parameters
///
/// * `proto_filename` - The path/name of the starting `.proto` file (e.g., "path/to/my_message.proto").
/// * `all_proto_files` - A map containing all known proto files, keyed by their filename,
///   along with their build metadata and parsed descriptors.
///
/// # Returns
///
/// A vector of [ProtoMetadata] structs, one for each unique transitive dependency
/// (excluding the starting file itself and well-known types).
pub fn get_proto_dependencies(
    proto_filename: String,
    all_proto_files: &HashMap<String, (&ProtoBuildTargetMetadata, &FileDescriptorProto)>,
) -> Vec<ProtoMetadata> {
    let mut proto_dependencies = IndexMap::new();
    get_transitive_proto_dependencies(
        proto_filename.clone(),
        all_proto_files,
        &mut proto_dependencies,
    );
    proto_dependencies.values().cloned().collect()
}

/// Recursively finds proto imports to find all transitive dependencies.
///
/// This helper function performs the depth-first traversal of the import graph.
/// It populates the `proto_dependencies` map with metadata for each encountered proto file,
/// skipping already visited files and Google's well-known types.
///
/// # Parameters
///
/// * `proto_file_name` - The filename of the current `.proto` file being processed.
/// * `all_proto_files` - A map containing all known proto files and their associated data.
/// * `proto_dependencies` - A mutable map to store the collected [ProtoMetadata] for dependencies,
///   keyed by proto filename. This map is populated by the function.
fn get_transitive_proto_dependencies(
    proto_file_name: String,
    all_proto_files: &HashMap<String, (&ProtoBuildTargetMetadata, &FileDescriptorProto)>,
    proto_dependencies: &mut IndexMap<String, ProtoMetadata>,
) {
    // exclude well-known protos, because those don't need to be transmitted for reflection.
    if sdv_vsidl_common::WELLKNOWN_PROTOS_TO_DESCRIPTOR.contains_key(&proto_file_name)
        || proto_dependencies.contains_key(&proto_file_name)
    {
        return;
    }

    if let Some((metadata, file_descriptor)) = all_proto_files.get(&proto_file_name) {
        proto_dependencies.insert(
            proto_file_name.clone(),
            ProtoMetadata {
                folder: metadata.folder.clone(),
                filename: proto_file_name,
                rust_build_target_name: metadata.target_name.clone(),
                rust_crate_name: metadata.crate_name.clone(),
            },
        );

        for dependency in &file_descriptor.dependency {
            get_transitive_proto_dependencies(
                dependency.clone(),
                all_proto_files,
                proto_dependencies,
            );
        }
    }
}

/// Extracts all Protobuf message definitions from a parsed [Catalog].
///
/// Iterates through all [FileDescriptorProto] instances within the catalog, extracting
/// each message definition and associating it with its [ProtoMetadata].
///
/// # Parameters
///
/// * `catalog` - The [Catalog] containing all parsed proto descriptors and metadata.
///
/// # Returns
///
/// A `Result` containing a [HashMap] where:
///   - Keys are the fully-qualified names of the Protobuf messages (e.g., "com.example.protos.MyMessage").
///   - Values are the corresponding [ProtoMessage] structs containing message details and metadata.
///
/// # Errors
///
/// Returns an error if any [FileDescriptorProto] within the catalog is missing its `package` declaration.
pub(crate) fn get_all_protobuf_messages(
    catalog: &Catalog,
) -> anyhow::Result<HashMap<String, ProtoMessage>> {
    let mut messages = HashMap::new();
    for (metadata, file) in &catalog.proto_descriptors {
        let package = file
            .package
            .as_ref()
            .ok_or(anyhow!(format!("Package is not set for {}", file.name())))?;

        for message in &file.message_type {
            messages.insert(
                format!("{package}.{}", message.name.as_ref().unwrap()),
                ProtoMessage {
                    name: message.name.as_ref().unwrap().to_string(),
                    package: package.to_string(),
                    proto_metadata: ProtoMetadata {
                        folder: metadata.folder.clone(),
                        filename: file.name.as_ref().unwrap().to_string(),
                        rust_build_target_name: metadata.target_name.clone(),
                        rust_crate_name: metadata.crate_name.clone(),
                    },
                },
            );
        }
    }

    Ok(messages)
}
